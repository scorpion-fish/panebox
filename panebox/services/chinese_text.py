def to_traditional(value: str | None) -> str:
    if not value:
        return value or ""
    return "".join(_SIMPLIFIED_TO_TRADITIONAL.get(ch, ch) for ch in value)


def to_simplified(value: str | None) -> str:
    if not value:
        return value or ""
    return "".join(_TRADITIONAL_TO_SIMPLIFIED.get(ch, ch) for ch in value)


def is_traditional_chinese_culture(culture_name: str | None) -> bool:
    """LocalizationService.IsTraditionalChineseCulture."""
    if not culture_name:
        return False
    normalized = culture_name.replace("_", "-").lower()
    return normalized.startswith("zh-hant") or normalized in ("zh-tw", "zh-hk", "zh-mo")
